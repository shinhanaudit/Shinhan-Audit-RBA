def get_legal_refs(industry: str, theme: str = "", subtopic: str = "") -> list[str]:
    """업권·테마·소제목 키워드로 관련 법령 목록을 반환한다.

    원문에서 법령을 직접 추출한 경우에는 이 함수를 쓰지 않아도 된다.
    추출 못한 항목의 '법령근거' 컬럼을 채울 때만 보조용으로 쓴다.
    """
    refs: list[str] = list(INDUSTRY_LAWS.get(industry, []))

    haystack = f"{theme} {subtopic}".lower()
    for keyword, laws in THEME_LAWS.items():
        if keyword in haystack:
            refs.extend(laws)

    # 중복 제거 (순서 유지)
    seen: set[str] = set()
    unique: list[str] = []
    for r in refs:
        if r not in seen:
            seen.add(r)
            unique.append(r)
    return unique
